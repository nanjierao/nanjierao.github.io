/** Which function a family's `flag` entries must trip. */
export type CorpusFunction = 'phones' | 'emails' | 'addresses' | 'terms' | 'videoTitle' | 'code';

export interface CorpusFamily {
  name: string;
  fn: CorpusFunction;
  /** When set, every `flag` entry needs a finding whose category contains this. */
  category?: string;
  /** Must produce a finding from `fn` (videoTitle: must be held back). */
  flag: string[];
  /**
   * Must produce no finding from any of findPhones, findEmails, findAddresses and
   * findSection15Terms (videoTitle: must be shown; code: scanned the way check-privacy scans
   * .js/.css files).
   */
  pass: string[];
}

export interface KnownLimit {
  family: string;
  text: string;
  expected: 'flag' | 'pass';
  reason: string;
}

