// Drawings for the sketch scenes (D68, D73): SVG path data on an 800 × 450 canvas. Each scene
// is a list of regions, drawn in story order (setting, person, device); inside a region the
// lines are drawn first and the pale fills fade in after them. Nothing in a drawing is text.
// The words that go with each region are in sketch-scenes.ts.
//
// The dorm, dining-hall, puppet and street drawings come from Jimmy's sketch prototype
// (Nov 24, 2026); the desk scene, the three teacher scenes and the parts that the hands-on
// steps change were drawn for the site in the same style.
import type { SceneId } from './sketch-scenes.ts';

export interface Shape {
  d: string;
  /** Line weight; left out for a color fill. */
  stroke?: 'ink' | 'thin';
  /** A pale fill under the lines. */
  fill?: 'screen' | 'warm' | 'rose';
  /** Names a piece that a hands-on step changes (the puppet, a data channel, the map cell). */
  part?: string;
}

export interface Region {
  /** Time to draw the region at normal speed, in milliseconds. */
  ms: number;
  shapes: Shape[];
}

export interface Drawing {
  regions: Region[];
  /** Named points on the canvas: where data leaves for the panel, and the pivots of parts. */
  anchors: Record<string, [x: number, y: number]>;
}

